// Generates the GitHub issue forms and labels from the roadmap (site/src/data/roadmap.ts), so their dropdowns name the same
// categories and rows: .github/ISSUE_TEMPLATE/bug.yml, works-in-play.yml and .github/labels.json. Run after adding or renaming a row
// or category: `node site/scripts/issue-forms.mjs`. The roadmap drift check reports when the files are out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const q = (s) => JSON.stringify(s);   // a JSON string is a valid YAML scalar
const options = (list) => list.map((o) => `        - ${q(o)}`).join('\n');
const platforms = ['Windows', 'Linux (native)', 'Linux (Proton)', 'macOS (Apple silicon)', 'macOS (Intel)'];

/** The dropdown text for a row: its name and id, so a reworded name still points at the row. */
export const rowOption = (r) => `${r.system} [${r.id}]`;

export function render(data) {
  const rows = data.categories.flatMap((c) => c.rows);
  const header = '# Generated by site/scripts/issue-forms.mjs from site/src/data/roadmap.ts; edit the script, not this file.\n';
  const bug = `${header}name: Bug report
description: Something in Meitou behaves differently from Kenshi, or breaks.
labels: [bug]
body:
  - type: markdown
    attributes:
      value: Thanks for testing Meitou. A report with the version, platform and log.txt can usually be acted on; one without often cannot.
  - type: input
    id: version
    attributes:
      label: Meitou version
      description: The version the launcher shows, e.g. 0.15.0 or 0.14.2-nightly.20261024.
    validations:
      required: true
  - type: dropdown
    id: platform
    attributes:
      label: Platform
      options:
${options(platforms)}
    validations:
      required: true
  - type: dropdown
    id: copy
    attributes:
      label: Kenshi copy
      options:
${options(['Steam', 'GOG', 'Other'])}
    validations:
      required: true
  - type: dropdown
    id: modded
    attributes:
      label: Mods
      options:
${options(['No mods', 'With mods (list them below)'])}
    validations:
      required: true
  - type: dropdown
    id: area
    attributes:
      label: Area
      description: The roadmap category it belongs to.
      options:
${options(data.categories.map((c) => c.name))}
    validations:
      required: true
  - type: textarea
    id: what
    attributes:
      label: What happened
    validations:
      required: true
  - type: textarea
    id: original
    attributes:
      label: What the original game does
    validations:
      required: true
  - type: textarea
    id: steps
    attributes:
      label: Steps to see it
      placeholder: "1. Load a save with ...\n2. ..."
    validations:
      required: true
  - type: textarea
    id: log
    attributes:
      label: log.txt
      description: Drag log.txt from the game's folder (next to MeitouClient) here. It keeps the last runs, so it still holds the bad one.
    validations:
      required: true
`;
  const works = `${header}name: Works in play
description: A roadmap system worked for you in play.
labels: [confirmed-works]
body:
  - type: markdown
    attributes:
      value: This turns "it works" into evidence on the roadmap (https://meitou.kenshi.wiki/roadmap).
  - type: dropdown
    id: row
    attributes:
      label: Roadmap system
      options:
${options(rows.map(rowOption))}
    validations:
      required: true
  - type: input
    id: version
    attributes:
      label: Meitou version
    validations:
      required: true
  - type: dropdown
    id: platform
    attributes:
      label: Platform
      options:
${options(platforms)}
    validations:
      required: true
  - type: textarea
    id: what
    attributes:
      label: What you did
      description: One or two lines are enough.
    validations:
      required: true
`;
  const labels = [
    { name: 'bug', color: 'd73a4a', description: 'Something does not work' },
    { name: 'parity', color: 'c5def5', description: 'Differs from the original game' },
    { name: 'confirmed-works', color: '0e8a16', description: 'Seen working in play' },
    { name: 'roadmap-drift', color: 'fbca04', description: 'The roadmap no longer matches GitHub' },
    { name: 'feedback', color: 'bfd4f2', description: 'Sent with the in-game feedback button' },
    ...data.categories.map((c) => ({ name: `area:${c.id}`, color: 'ededed', description: `Roadmap category: ${c.name}` })),
  ];
  return {
    '.github/ISSUE_TEMPLATE/bug.yml': bug,
    '.github/ISSUE_TEMPLATE/works-in-play.yml': works,
    '.github/labels.json': JSON.stringify(labels, null, 2) + '\n',
  };
}

export const root = new URL('../../', import.meta.url);
export const loadRoadmap = () => import(new URL('site/src/data/roadmap.ts', root).href);

/** The files that differ from what the roadmap gives. */
export async function stale() {
  const files = render(await loadRoadmap());
  return Object.entries(files).filter(([path, text]) => {
    try { return readFileSync(new URL(path, root), 'utf8') !== text; } catch { return true; }
  }).map(([path]) => path);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = render(await loadRoadmap());
  for (const [path, text] of Object.entries(files)) writeFileSync(new URL(path, root), text);
  console.log(`wrote ${Object.keys(files).join(', ')}`);
}
